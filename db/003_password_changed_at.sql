-- =============================================================================
-- 003_password_changed_at.sql — отзыв сессий при смене пароля.
--
-- Инкремент поверх db/schema.sql (Phase 1) и db/002_auth_phase2.sql.
-- Изменение также внесено в schema.sql, чтобы чистый bootstrap получал его
-- сразу; этот файл нужен, чтобы уже поднятый инстанс Railway обновить на месте
-- без drop/recreate — данные в нём сохраняются.
--
-- Идемпотентно: безопасно запускать повторно.
--
-- ─── Зачем ───────────────────────────────────────────────────────────────────
-- Supabase отзывал чужие сессии через admin.auth.admin.signOut(token,'others').
-- Подписанная cookie-сессия stateless: отдельный токен отозвать нечем, список
-- выданных токенов нигде не хранится.
--
-- Дешёвая замена без таблицы сессий: одна отметка времени на пользователя.
-- Токен несёт iat (момент выдачи); если iat раньше последней смены пароля —
-- токен выдан до неё и больше не действителен. Проверка живёт в getActor()
-- (src/lib/auth/actor.ts) и стоит ноль дополнительных запросов: колонка
-- читается тем же JOIN, что и роль сотрудника.
--
-- Сравнение идёт с точностью до секунды (date_trunc): iat в токене — целые
-- секунды unix, а password_changed_at — микросекунды. Без усечения сессия,
-- выданная в ту же секунду, в которую сменили пароль, отвергалась бы как
-- «старая» — и пользователь не мог бы войти сразу после смены пароля.

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMPTZ;

COMMENT ON COLUMN public.users.password_changed_at IS
  'Момент последней смены пароля. Сессии с iat раньше этого значения считаются '
  'отозванными (см. getActor в src/lib/auth/actor.ts). NULL — пароль ни разу '
  'не менялся, все сессии действительны.';
